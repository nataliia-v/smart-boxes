export type MessageKey = keyof typeof messages;
export function translate(locale: Locale, key: MessageKey, params: Record<string, string | number> = {}) {
  return messages[key][locale === 'uk' ? 0 : 1].replace(/\{(\w+)\}/g, (match, name: string) => String(params[name] ?? match));
}
export function itemCount(locale: Locale, count: number) {
  const category = new Intl.PluralRules(locale).select(count);
  const word = locale === 'en' ? (category === 'one' ? 'item' : 'items') : category === 'one' ? 'річ' : category === 'few' ? 'речі' : 'речей';
  return `${new Intl.NumberFormat(locale).format(count)} ${word}`;
}
