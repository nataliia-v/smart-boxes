export type Locale = 'uk' | 'en';
export const localeCookie = 'smartbox-locale';

export function resolveLocale(saved?: string, acceptLanguage = ''): Locale {
  if (saved === 'uk' || saved === 'en') return saved;
  const preferences = acceptLanguage.split(',').map((entry, index) => {
    const [tag, ...params] = entry.trim().split(';');
    const quality = params.find(p => p.trim().startsWith('q='));
    return { tag: tag.toLowerCase(), q: quality ? Number(quality.trim().slice(2)) : 1, index };
  }).filter(p => p.tag && Number.isFinite(p.q) && p.q > 0 && p.q <= 1)
    .sort((a, b) => b.q - a.q || a.index - b.index);
  return preferences[0]?.tag.split('-')[0] === 'uk' ? 'uk' : 'en';
}

